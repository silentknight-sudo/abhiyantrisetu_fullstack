import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { hmac, safeEqualHex } from '../../common/crypto';
import { presignS3 } from './sigv4';

export const STORAGE_PROVIDER = Symbol('STORAGE_PROVIDER');

export interface UploadTarget {
  method: 'PUT';
  url: string;
  /** Headers the client must send with the upload, exactly. */
  headers: Record<string, string>;
}

/** Where photos live. Clients upload and download directly with short-lived signed URLs. */
export interface StorageProvider {
  presignUpload(key: string, contentType: string, expiresIn: number): UploadTarget;
  presignDownload(key: string, expiresIn: number): string;
}

/** Amazon S3 (Mumbai). The bucket stays private; every URL is signed and expires. */
export class S3StorageProvider implements StorageProvider {
  private readonly host: string;
  constructor(
    private readonly bucket: string,
    private readonly region: string,
    private readonly accessKeyId: string,
    private readonly secretAccessKey: string,
  ) {
    this.host = `${bucket}.s3.${region}.amazonaws.com`;
  }

  presignUpload(key: string, contentType: string, expiresIn: number): UploadTarget {
    const headers = { 'Content-Type': contentType };
    return { method: 'PUT', headers, url: this.sign('PUT', key, expiresIn, headers) };
  }

  presignDownload(key: string, expiresIn: number) {
    return this.sign('GET', key, expiresIn);
  }

  private sign(
    method: 'GET' | 'PUT',
    key: string,
    expiresIn: number,
    signedHeaders?: Record<string, string>,
  ) {
    return presignS3({
      method,
      host: this.host,
      key,
      region: this.region,
      accessKeyId: this.accessKeyId,
      secretAccessKey: this.secretAccessKey,
      expiresIn,
      signedHeaders,
    });
  }
}

/**
 * Development and tests: files on local disk, served by this API through
 * /v1/uploads/local with the same short-lived signed links as S3.
 */
export class LocalStorageProvider implements StorageProvider {
  constructor(
    private readonly dir: string,
    private readonly baseUrl: string,
    private readonly secret: string,
  ) {}

  private link(method: 'GET' | 'PUT', key: string, expiresIn: number, contentType = '') {
    const exp = Math.floor(Date.now() / 1000) + expiresIn;
    const sig = this.signature(method, key, exp, contentType);
    const q = new URLSearchParams({ key, exp: String(exp), sig });
    return `${this.baseUrl}/v1/uploads/local?${q}`;
  }

  signature(method: string, key: string, exp: number, contentType = '') {
    return hmac(this.secret, `${method}\n${key}\n${exp}\n${contentType}`);
  }

  presignUpload(key: string, contentType: string, expiresIn: number): UploadTarget {
    return {
      method: 'PUT',
      headers: { 'Content-Type': contentType },
      url: this.link('PUT', key, expiresIn, contentType),
    };
  }

  presignDownload(key: string, expiresIn: number) {
    return this.link('GET', key, expiresIn);
  }

  verify(method: 'GET' | 'PUT', key: string, exp: number, sig: string, contentType = '') {
    if (!Number.isFinite(exp) || exp < Date.now() / 1000) return false;
    return (
      /^[0-9a-f]{64}$/.test(sig) && safeEqualHex(sig, this.signature(method, key, exp, contentType))
    );
  }

  private file(key: string) {
    // Keys are generated by the API (u/<uuid>/<purpose>/<uuid>.<ext>); refuse anything else.
    if (!/^u\/[0-9a-f-]{36}\/[a-z_]+\/[0-9a-f-]{36}\.(jpg|png|webp|heic)$/.test(key)) {
      throw new Error('Bad key');
    }
    return path.join(this.dir, key);
  }

  async write(key: string, body: Buffer, contentType: string) {
    const file = this.file(key);
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, body);
    await writeFile(`${file}.type`, contentType);
  }

  async read(key: string) {
    const file = this.file(key);
    const [body, type] = await Promise.all([readFile(file), readFile(`${file}.type`, 'utf8')]);
    return { body, contentType: type };
  }
}
